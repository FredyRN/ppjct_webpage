function getPreferredLanguage() {
  const saved = localStorage.getItem('lang');
  if (saved && (saved === 'es' || saved === 'en')) return saved;
  const navLang = navigator.language || navigator.userLanguage || '';
  return navLang.toLowerCase().startsWith('es') ? 'es' : 'en';
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;

  const dict = translations[lang];

  // Update document title & meta description
  if (dict.pageTitle) document.title = dict.pageTitle;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict.pageDesc) metaDesc.setAttribute('content', dict.pageDesc);

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // Update language toggle button label
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.innerHTML = lang === 'es' ? '🌐 EN' : '🌐 ES';
    btn.setAttribute('aria-label', lang === 'es' ? 'Switch to English' : 'Cambiar a Español');
  }

  // Update WhatsApp link text depending on language
  const waBtnHero = document.getElementById('wa-btn-hero');
  const waBtnContact = document.getElementById('wa-btn-contact');
  const waText = lang === 'es' 
    ? encodeURIComponent("Hola Fredy, quiero automatizar mi negocio")
    : encodeURIComponent("Hi Fredy, I want to automate my business");

  if (waBtnHero) waBtnHero.href = `https://wa.me/573000000000?text=${waText}`;
  if (waBtnContact) waBtnContact.href = `https://wa.me/573000000000?text=${waText}`;
}

document.addEventListener('DOMContentLoaded', () => {
  const currentLang = getPreferredLanguage();
  setLanguage(currentLang);

  const toggleBtn = document.getElementById('lang-toggle');
  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      const activeLang = localStorage.getItem('lang') || 'es';
      const newLang = activeLang === 'es' ? 'en' : 'es';
      setLanguage(newLang);
    });
  }
});
